; MARK: EVAL_KEYBOARD
; Checks for WASD keys and move up,left,down,right
EVAL_KEYBOARD
    LDX MOVEMENT_COOLDOWN_CTR   ; if MOVEMENT_COOLDOWN_CTR == 0: check movement
    BEQ _MOVEMENT
    DEC MOVEMENT_COOLDOWN_CTR   ; else: MOVEMENT_COOLDOWN_CTR-- and check keys again next frame
    RTS
_MOVEMENT
    CMP #"W"
    BNE _CHECK_NEXT_MOVE_KEY0
    JMP _UP
_CHECK_NEXT_MOVE_KEY0
    CMP #"A"
    BNE _CHECK_NEXT_MOVE_KEY1
    JMP _LEFT
_CHECK_NEXT_MOVE_KEY1
    CMP #"D"
    BNE _CHECK_NEXT_MOVE_KEY2
    JMP _RIGHT
_CHECK_NEXT_MOVE_KEY2
    CMP #"S"
    BNE _CHECK_NEXT_MOVE_KEY3
    JMP _DOWN
_CHECK_NEXT_MOVE_KEY3
    RTS

_UP
    LDA SPR0_Y
    CMP #21+25 
    BNE _MOVE_UP
    RTS
_MOVE_UP
    SEC
    SBC #32 
    STA SPR0_Y

    LDA CARD_PTR16+0 ; CARD_PTR16-= 40*4 (four rows)
    SEC
    SBC #(40*4)
    STA CARD_PTR16+0
    LDA CARD_PTR16+1
    SBC #0
    STA CARD_PTR16+1

    JMP _SET_MOVEMENT_COOLDOWN
_DOWN
    LDA SPR0_Y
    CMP #21+25+(32*3)
    BNE _MOVE_DOWN
    RTS
_MOVE_DOWN
    CLC
    ADC #32 
    STA SPR0_Y

    LDA CARD_PTR16+0 ; CARD_PTR16+= 40*4 (four rows)
    CLC
    ADC #(40*4)
    STA CARD_PTR16+0
    LDA CARD_PTR16+1
    ADC #0
    STA CARD_PTR16+1

    JMP _SET_MOVEMENT_COOLDOWN
_LEFT
    LDA SPR0_X
    CMP #12+8
    BNE _MOVE_LEFT
    RTS
_MOVE_LEFT
    SEC
    SBC #16 
    STA SPR0_X

    LDA CARD_PTR16+0 ; CARD_PTR16-= 4 (four columns)
    SEC
    SBC #4
    STA CARD_PTR16+0
    LDA CARD_PTR16+1
    SBC #0
    STA CARD_PTR16+1

    JMP _SET_MOVEMENT_COOLDOWN
_RIGHT
    LDA SPR0_X
    CMP #12+8+(16*5)
    BNE _MOVE_RIGHT
    RTS
_MOVE_RIGHT
    CLC
    ADC #16 
    STA SPR0_X

    LDA CARD_PTR16+0 ; CARD_PTR16+= 4 (four columns)
    CLC
    ADC #4
    STA CARD_PTR16+0
    LDA CARD_PTR16+1
    ADC #0
    STA CARD_PTR16+1

    JMP _SET_MOVEMENT_COOLDOWN
_SET_MOVEMENT_COOLDOWN
    LDA MOVEMENT_COOLDOWN       ; MOVEMENT_COOLDOWN_CTR = MOVEMENT_COOLDOWN
    STA MOVEMENT_COOLDOWN_CTR
    RTS